#!/bin/bash

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
SPECTRAL_ROOT="${PROJECT_ROOT}/Spectral-master"
cd "${SPECTRAL_ROOT}"

PYTHON=${PYTHON:-python}
SEED=${SEED:-0}
MODELS=${MODELS:-"DLinear iTransformer"}
DATASETS=${DATASETS:-"ETTh1 ETTh2 ETTm1 ETTm2 exchange_rate weather"}
PRED_LEN=${PRED_LEN:-96}

BUFFER_CONTEXT_SIZE=${BUFFER_CONTEXT_SIZE:-10}
STEPS=${STEPS:-3}
BATCH_SIZE=${BATCH_SIZE:-48}
PAAS=${PAAS:-True}
PERIOD_N=${PERIOD_N:-1}
FAST_ADAPTATION=${FAST_ADAPTATION:-True}
ADAPTIVE_LR=${ADAPTIVE_LR:-True}
PER_BATCH_LR_RESET=${PER_BATCH_LR_RESET:-True}

KAPPA=${KAPPA:-1.0}
EMA_ALPHA=${EMA_ALPHA:-0.1}
RESIDUAL_SCALE=${RESIDUAL_SCALE:-ewma_std}
WARMUP_BATCHES=${WARMUP_BATCHES:-3}
ENABLE_SELECTIVE=${ENABLE_SELECTIVE:-True}
SPECTRAL_MODE=${SPECTRAL_MODE:-concat}
SPECTRAL_USAGE=${SPECTRAL_USAGE:-context_only}
SPECTRAL_SOURCE=${SPECTRAL_SOURCE:-residual_profile}
SPECTRAL_REPR=${SPECTRAL_REPR:-real_imag}
SPECTRAL_K=${SPECTRAL_K:-8}
SPECTRAL_HISTORY_SIZE=${SPECTRAL_HISTORY_SIZE:-8}
SPECTRAL_INCLUDE_POWER_RATIO=${SPECTRAL_INCLUDE_POWER_RATIO:-True}
SPECTRAL_INCLUDE_RESIDUAL_STATS=${SPECTRAL_INCLUDE_RESIDUAL_STATS:-True}
SPECTRAL_MIN_POWER_RATIO_FOR_DIRECT=${SPECTRAL_MIN_POWER_RATIO_FOR_DIRECT:-0.20}
USE_CONTEXT_PROJECTION=${USE_CONTEXT_PROJECTION:-True}
CONTEXT_PROJECTION_DIM=${CONTEXT_PROJECTION_DIM:-8}
MAX_CONTEXT_DIM_FOR_FULL_ADAPTER=${MAX_CONTEXT_DIM_FOR_FULL_ADAPTER:-16}
PARAM_BUDGET_MULTIPLIER=${PARAM_BUDGET_MULTIPLIER:-1.25}
ENABLE_DIRECT_SPECTRAL_CORRECTION=${ENABLE_DIRECT_SPECTRAL_CORRECTION:-False}

if [ -z "${VARIANT_TAG:-}" ]; then
  VARIANT_TAG="${SPECTRAL_MODE}_${SPECTRAL_SOURCE}_${SPECTRAL_REPR}_hist${SPECTRAL_HISTORY_SIZE}_proj${USE_CONTEXT_PROJECTION}_dim${CONTEXT_PROJECTION_DIM}_selective_${ENABLE_SELECTIVE}"
fi
VARIANT_TAG=$(echo "$VARIANT_TAG" | tr ' /' '__')

read -r -a MODEL_LIST <<< "$MODELS"
read -r -a DATASET_LIST <<< "$DATASETS"

for MODEL in "${MODEL_LIST[@]}"; do
  for DATASET in "${DATASET_LIST[@]}"; do
    RUN_SEQ_LEN=${SEQ_LEN:-96}
    RUN_LABEL_LEN=${LABEL_LEN:-48}
    RUN_PRED_LEN=${PRED_LEN}
    RUN_TEST_BATCH_SIZE=${TEST_BATCH_SIZE:-128}

    CHECKPOINT_DIR="./checkpoints/${MODEL}/${DATASET}_${RUN_PRED_LEN}/"
    RESULT_DIR="./results/COSA_SELECT/${VARIANT_TAG}/"
    OUTPUT="./results/summary/COSA_SELECT/${VARIANT_TAG}/${MODEL}/${DATASET}/pred${RUN_PRED_LEN}_seed${SEED}.log"
    LOG_CSV="./results/summary/COSA_SELECT/${VARIANT_TAG}/${MODEL}/${DATASET}/pred${RUN_PRED_LEN}_seed${SEED}_batches.csv"
    mkdir -p "$(dirname "${OUTPUT}")"

    ${PYTHON} main.py \
      SEED ${SEED} \
      DATA_LOADER.NUM_WORKERS 0 \
      DATA.BASE_DIR ./data/ \
      DATA.NAME ${DATASET} \
      DATA.SEQ_LEN ${RUN_SEQ_LEN} \
      DATA.LABEL_LEN ${RUN_LABEL_LEN} \
      DATA.PRED_LEN ${RUN_PRED_LEN} \
      MODEL.NAME ${MODEL} \
      MODEL.seq_len ${RUN_SEQ_LEN} \
      MODEL.label_len ${RUN_LABEL_LEN} \
      MODEL.pred_len ${RUN_PRED_LEN} \
      TRAIN.ENABLE False \
      TRAIN.CHECKPOINT_DIR ${CHECKPOINT_DIR} \
      TEST.ENABLE False \
      TEST.BATCH_SIZE ${RUN_TEST_BATCH_SIZE} \
      TTA.ENABLE True \
      TTA.SOLVER.BASE_LR 0.001 \
      TTA.SOLVER.WEIGHT_DECAY 0.0001 \
      TTA.COSA.BATCH_SIZE ${BATCH_SIZE} \
      TTA.COSA.STEPS ${STEPS} \
      TTA.COSA.BUFFER_CONTEXT_SIZE ${BUFFER_CONTEXT_SIZE} \
      TTA.COSA.PAAS ${PAAS} \
      TTA.COSA.PERIOD_N ${PERIOD_N} \
      TTA.COSA.FAST_ADAPTATION ${FAST_ADAPTATION} \
      TTA.COSA.ADAPTIVE_LR ${ADAPTIVE_LR} \
      TTA.COSA.PER_BATCH_LR_RESET ${PER_BATCH_LR_RESET} \
      TTA.COSA.SELECT.ENABLE_SELECTIVE ${ENABLE_SELECTIVE} \
      TTA.COSA.SELECT.KAPPA ${KAPPA} \
      TTA.COSA.SELECT.EMA_ALPHA ${EMA_ALPHA} \
      TTA.COSA.SELECT.RESIDUAL_SCALE ${RESIDUAL_SCALE} \
      TTA.COSA.SELECT.WARMUP_BATCHES ${WARMUP_BATCHES} \
      TTA.COSA.SELECT.SPECTRAL_MODE ${SPECTRAL_MODE} \
      TTA.COSA.SELECT.SPECTRAL_USAGE ${SPECTRAL_USAGE} \
      TTA.COSA.SELECT.SPECTRAL_SOURCE ${SPECTRAL_SOURCE} \
      TTA.COSA.SELECT.SPECTRAL_REPR ${SPECTRAL_REPR} \
      TTA.COSA.SELECT.SPECTRAL_K ${SPECTRAL_K} \
      TTA.COSA.SELECT.SPECTRAL_HISTORY_SIZE ${SPECTRAL_HISTORY_SIZE} \
      TTA.COSA.SELECT.SPECTRAL_INCLUDE_POWER_RATIO ${SPECTRAL_INCLUDE_POWER_RATIO} \
      TTA.COSA.SELECT.SPECTRAL_INCLUDE_RESIDUAL_STATS ${SPECTRAL_INCLUDE_RESIDUAL_STATS} \
      TTA.COSA.SELECT.SPECTRAL_MIN_POWER_RATIO_FOR_DIRECT ${SPECTRAL_MIN_POWER_RATIO_FOR_DIRECT} \
      TTA.COSA.SELECT.USE_CONTEXT_PROJECTION ${USE_CONTEXT_PROJECTION} \
      TTA.COSA.SELECT.CONTEXT_PROJECTION_DIM ${CONTEXT_PROJECTION_DIM} \
      TTA.COSA.SELECT.MAX_CONTEXT_DIM_FOR_FULL_ADAPTER ${MAX_CONTEXT_DIM_FOR_FULL_ADAPTER} \
      TTA.COSA.SELECT.PARAM_BUDGET_MULTIPLIER ${PARAM_BUDGET_MULTIPLIER} \
      TTA.COSA.SELECT.ENABLE_DIRECT_SPECTRAL_CORRECTION ${ENABLE_DIRECT_SPECTRAL_CORRECTION} \
      TTA.COSA.SELECT.LOG_CSV_PATH ${LOG_CSV} \
      RESULT_DIR ${RESULT_DIR} > "${OUTPUT}"
  done
done
