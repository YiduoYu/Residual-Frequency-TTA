#!/bin/bash

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"
SPECTRAL_ROOT="${PROJECT_ROOT}/Spectral-master"
cd "${SPECTRAL_ROOT}"

PYTHON=${PYTHON:-python}
DRY_RUN=${DRY_RUN:-False}

MODELS=${MODELS:-"DLinear iTransformer"}
DATASETS=${DATASETS:-"ETTh1 ETTh2 ETTm1 ETTm2 exchange_rate weather"}
PRED_LENS=${PRED_LENS:-"96"}
SEEDS=${SEEDS:-"0"}

SEQ_LEN=${SEQ_LEN:-96}
LABEL_LEN=${LABEL_LEN:-48}
TEST_BATCH_SIZE=${TEST_BATCH_SIZE:-128}
NUM_WORKERS=${NUM_WORKERS:-0}

BUFFER_CONTEXT_SIZE=${BUFFER_CONTEXT_SIZE:-10}
STEPS=${STEPS:-3}
BATCH_SIZE=${BATCH_SIZE:-48}
PAAS=${PAAS:-True}
PERIOD_N=${PERIOD_N:-1}
FAST_ADAPTATION=${FAST_ADAPTATION:-True}
ADAPTIVE_LR=${ADAPTIVE_LR:-True}
PER_BATCH_LR_RESET=${PER_BATCH_LR_RESET:-True}
BASE_LR=${BASE_LR:-0.001}
WEIGHT_DECAY=${WEIGHT_DECAY:-0.0001}

SPECTRAL_MODE=${SPECTRAL_MODE:-concat}
SPECTRAL_USAGE=${SPECTRAL_USAGE:-direct}
SPECTRAL_SOURCE=${SPECTRAL_SOURCE:-residual_profile}
SPECTRAL_REPR=${SPECTRAL_REPR:-real_imag}
SPECTRAL_K=${SPECTRAL_K:-8}
SPECTRAL_HISTORY_SIZE=${SPECTRAL_HISTORY_SIZE:-8}
SPECTRAL_INCLUDE_POWER_RATIO=${SPECTRAL_INCLUDE_POWER_RATIO:-True}
SPECTRAL_INCLUDE_RESIDUAL_STATS=${SPECTRAL_INCLUDE_RESIDUAL_STATS:-True}
SPECTRAL_MIN_POWER_RATIO_FOR_DIRECT=${SPECTRAL_MIN_POWER_RATIO_FOR_DIRECT:-0.20}

ENABLE_DIRECT_CORRECTION=${ENABLE_DIRECT_CORRECTION:-${ENABLE_DIRECT_SPECTRAL_CORRECTION:-True}}
GATE_MODE=${GATE_MODE:-${SPECTRAL_GATE_MODE:-unidirectional}}
ENABLE_REFERENCE_CONTENT_INJECTION=${ENABLE_REFERENCE_CONTENT_INJECTION:-False}
USE_GLOBAL_GATE=${USE_GLOBAL_GATE:-True}
GLOBAL_GATE_FEATURES=${GLOBAL_GATE_FEATURES:-hs,l2,low_freq_ratio}
ENABLE_REVIN_ON_SPECTRAL_PATH=${ENABLE_REVIN_ON_SPECTRAL_PATH:-False}
WINDOW_TYPE=${WINDOW_TYPE:-hann}
OUT_PROJ=${OUT_PROJ:-${SPECTRAL_OUT_PROJ:-diagonal}}
FFT_PRECISION=${FFT_PRECISION:-fp32}
FFT_LENGTH_MODE=${FFT_LENGTH_MODE:-exact}

USE_CONTEXT_PROJECTION=${USE_CONTEXT_PROJECTION:-True}
CONTEXT_PROJECTION_DIM=${CONTEXT_PROJECTION_DIM:-8}
MAX_CONTEXT_DIM_FOR_FULL_ADAPTER=${MAX_CONTEXT_DIM_FOR_FULL_ADAPTER:-16}
PARAM_BUDGET_MULTIPLIER=${PARAM_BUDGET_MULTIPLIER:-1.25}

if [ -z "${VARIANT_TAG:-}" ]; then
  VARIANT_TAG="scheme6_${SPECTRAL_USAGE}_${GATE_MODE}_${WINDOW_TYPE}_${OUT_PROJ}_globalgate${USE_GLOBAL_GATE}_hist${SPECTRAL_HISTORY_SIZE}"
fi
VARIANT_TAG=$(echo "${VARIANT_TAG}" | tr ' /,' '___')

read -r -a MODEL_LIST <<< "${MODELS}"
read -r -a DATASET_LIST <<< "${DATASETS}"
read -r -a PRED_LEN_LIST <<< "${PRED_LENS}"
read -r -a SEED_LIST <<< "${SEEDS}"
read -r -a PYTHON_CMD <<< "${PYTHON}"

is_true() {
  case "${1}" in
    True|true|1|yes|YES|y|Y) return 0 ;;
    *) return 1 ;;
  esac
}

run_to_log() {
  if is_true "${DRY_RUN}"; then
    printf 'DRY_RUN:'
    printf ' %q' "$@"
    printf '\n'
  else
    "$@" > "${OUTPUT}"
  fi
}

for MODEL in "${MODEL_LIST[@]}"; do
  for DATASET in "${DATASET_LIST[@]}"; do
    for RUN_PRED_LEN in "${PRED_LEN_LIST[@]}"; do
      for SEED in "${SEED_LIST[@]}"; do
        CHECKPOINT_DIR="./checkpoints/${MODEL}/${DATASET}_${RUN_PRED_LEN}/"
        RESULT_DIR="./results/COSA_SCHEME6/${VARIANT_TAG}/"
        OUTPUT="./results/summary/COSA_SCHEME6/${VARIANT_TAG}/${MODEL}/${DATASET}/pred${RUN_PRED_LEN}_seed${SEED}.log"
        LOG_CSV="./results/summary/COSA_SCHEME6/${VARIANT_TAG}/${MODEL}/${DATASET}/pred${RUN_PRED_LEN}_seed${SEED}_batches.csv"
        mkdir -p "$(dirname "${OUTPUT}")"

        run_to_log "${PYTHON_CMD[@]}" main.py \
          SEED "${SEED}" \
          DATA_LOADER.NUM_WORKERS "${NUM_WORKERS}" \
          DATA.BASE_DIR ./data/ \
          DATA.NAME "${DATASET}" \
          DATA.SEQ_LEN "${SEQ_LEN}" \
          DATA.LABEL_LEN "${LABEL_LEN}" \
          DATA.PRED_LEN "${RUN_PRED_LEN}" \
          MODEL.NAME "${MODEL}" \
          MODEL.seq_len "${SEQ_LEN}" \
          MODEL.label_len "${LABEL_LEN}" \
          MODEL.pred_len "${RUN_PRED_LEN}" \
          TRAIN.ENABLE False \
          TRAIN.CHECKPOINT_DIR "${CHECKPOINT_DIR}" \
          TEST.ENABLE False \
          TEST.BATCH_SIZE "${TEST_BATCH_SIZE}" \
          TTA.ENABLE True \
          TTA.SOLVER.BASE_LR "${BASE_LR}" \
          TTA.SOLVER.WEIGHT_DECAY "${WEIGHT_DECAY}" \
          TTA.COSA.BATCH_SIZE "${BATCH_SIZE}" \
          TTA.COSA.STEPS "${STEPS}" \
          TTA.COSA.BUFFER_CONTEXT_SIZE "${BUFFER_CONTEXT_SIZE}" \
          TTA.COSA.PAAS "${PAAS}" \
          TTA.COSA.PERIOD_N "${PERIOD_N}" \
          TTA.COSA.FAST_ADAPTATION "${FAST_ADAPTATION}" \
          TTA.COSA.ADAPTIVE_LR "${ADAPTIVE_LR}" \
          TTA.COSA.PER_BATCH_LR_RESET "${PER_BATCH_LR_RESET}" \
          TTA.COSA.SPECTRAL.MODE "${SPECTRAL_MODE}" \
          TTA.COSA.SPECTRAL.USAGE "${SPECTRAL_USAGE}" \
          TTA.COSA.SPECTRAL.SOURCE "${SPECTRAL_SOURCE}" \
          TTA.COSA.SPECTRAL.REPR "${SPECTRAL_REPR}" \
          TTA.COSA.SPECTRAL.K "${SPECTRAL_K}" \
          TTA.COSA.SPECTRAL.HISTORY_SIZE "${SPECTRAL_HISTORY_SIZE}" \
          TTA.COSA.SPECTRAL.INCLUDE_POWER_RATIO "${SPECTRAL_INCLUDE_POWER_RATIO}" \
          TTA.COSA.SPECTRAL.INCLUDE_RESIDUAL_STATS "${SPECTRAL_INCLUDE_RESIDUAL_STATS}" \
          TTA.COSA.SPECTRAL.MIN_POWER_RATIO_FOR_DIRECT "${SPECTRAL_MIN_POWER_RATIO_FOR_DIRECT}" \
          TTA.COSA.SPECTRAL.USE_CONTEXT_PROJECTION "${USE_CONTEXT_PROJECTION}" \
          TTA.COSA.SPECTRAL.CONTEXT_PROJECTION_DIM "${CONTEXT_PROJECTION_DIM}" \
          TTA.COSA.SPECTRAL.MAX_CONTEXT_DIM_FOR_FULL_ADAPTER "${MAX_CONTEXT_DIM_FOR_FULL_ADAPTER}" \
          TTA.COSA.SPECTRAL.PARAM_BUDGET_MULTIPLIER "${PARAM_BUDGET_MULTIPLIER}" \
          TTA.COSA.SPECTRAL.ENABLE_DIRECT_CORRECTION "${ENABLE_DIRECT_CORRECTION}" \
          TTA.COSA.SPECTRAL.GATE_MODE "${GATE_MODE}" \
          TTA.COSA.SPECTRAL.ENABLE_REFERENCE_CONTENT_INJECTION "${ENABLE_REFERENCE_CONTENT_INJECTION}" \
          TTA.COSA.SPECTRAL.USE_GLOBAL_GATE "${USE_GLOBAL_GATE}" \
          TTA.COSA.SPECTRAL.GLOBAL_GATE_FEATURES "${GLOBAL_GATE_FEATURES}" \
          TTA.COSA.SPECTRAL.ENABLE_REVIN_ON_SPECTRAL_PATH "${ENABLE_REVIN_ON_SPECTRAL_PATH}" \
          TTA.COSA.SPECTRAL.WINDOW_TYPE "${WINDOW_TYPE}" \
          TTA.COSA.SPECTRAL.OUT_PROJ "${OUT_PROJ}" \
          TTA.COSA.SPECTRAL.FFT_PRECISION "${FFT_PRECISION}" \
          TTA.COSA.SPECTRAL.FFT_LENGTH_MODE "${FFT_LENGTH_MODE}" \
          TTA.COSA.SPECTRAL.LOG_CSV_PATH "${LOG_CSV}" \
          RESULT_DIR "${RESULT_DIR}"
      done
    done
  done
done
